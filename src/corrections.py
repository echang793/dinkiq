"""Manual point corrections, kept apart from the derived points.json.

points.json is regenerated by every (re)analysis and wiped by reprocess, so a fix written
into it was silently lost. A correction is stored here instead, keyed by the START TIME of
the rally it was made on -- rally indices shift when detection changes, times mostly don't --
and re-applied to whatever rallies the next analysis finds.
"""

from pathlib import Path

from jsonio import atomic_write_json, load_json

FILE = "corrections.json"
START_TOL_S = 1.0   # a re-detected rally this close to the corrected one is the same rally


def load(sdir: Path) -> list[dict]:
    data = load_json(sdir / FILE)
    items = data.get("points") if isinstance(data, dict) else None
    return [c for c in items if isinstance(c, dict) and "start" in c] if isinstance(items, list) else []


def _save(sdir: Path, items: list[dict]) -> None:
    atomic_write_json(sdir / FILE, {"points": items})


def set_correction(sdir: Path, start: float, winner: str, unforced_error: bool | None) -> None:
    """Record (or replace) the correction for the rally starting at `start`."""
    items = [c for c in load(sdir) if abs(c["start"] - start) > START_TOL_S / 2]
    items.append({"start": round(float(start), 2), "winner": winner, "unforced_error": unforced_error})
    _save(sdir, sorted(items, key=lambda c: c["start"]))


def remove_correction(sdir: Path, start: float) -> None:
    _save(sdir, [c for c in load(sdir) if abs(c["start"] - start) > START_TOL_S / 2])


def original(outcome: dict) -> dict:
    """The heuristic's own answer for an outcome, with any correction taken back off."""
    out = {k: v for k, v in outcome.items()
           if k not in ("corrected", "auto_winner", "auto_unforced_error")}
    if outcome.get("corrected"):
        out["winner"] = outcome.get("auto_winner", outcome.get("winner"))
        out["unforced_error"] = outcome.get("auto_unforced_error", outcome.get("unforced_error"))
    return out


def apply(outcomes: list[dict], rallies: list[dict], items: list[dict]) -> list[dict]:
    """New outcome list with each correction laid onto the rally it belongs to: the nearest
    rally start within START_TOL_S, each rally taking at most one. A correction whose rally
    is gone is dropped. The heuristic's answer is kept on the row (auto_*) so it can be undone."""
    out = [original(o) for o in outcomes]
    taken: set[int] = set()
    for c in items:
        cands = [(abs(r["start"] - c["start"]), i) for i, r in enumerate(rallies)
                 if i < len(out) and i not in taken and abs(r["start"] - c["start"]) <= START_TOL_S]
        if not cands:
            continue
        i = min(cands)[1]
        taken.add(i)
        row = out[i]
        row["auto_winner"], row["auto_unforced_error"] = row["winner"], row["unforced_error"]
        row["winner"] = c["winner"]
        if c.get("unforced_error") is not None:
            row["unforced_error"] = c["unforced_error"]
        row["corrected"] = True
    return out
